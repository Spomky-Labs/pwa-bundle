<?php

declare(strict_types=1);

namespace SpomkyLabs\PwaBundle\Tests\Functional;

use const E_USER_DEPRECATED;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use PHPUnit\Framework\TestCase;
use SpomkyLabs\PwaBundle\SpomkyLabsPwaBundle;
use function str_contains;
use Symfony\Component\Config\Definition\Configuration;
use Symfony\Component\Config\Definition\Processor;
use Symfony\Component\DependencyInjection\ContainerBuilder;

/**
 * Enabling the favicons also generates the iOS startup images, about twenty full-screen PNGs. That default
 * goes away in 2.0.0, so an application relying on it is told to make its choice now. Its startup images
 * are generated exactly as before in the meantime.
 *
 * What is tested here as much as the deprecation itself is its absence: an application that already made
 * its choice, or that generates no favicon, has nothing to change.
 */
final class StartupImagesDefaultDeprecationTest extends TestCase
{
    private const FAVICONS = [
        'enabled' => true,
        'default' => [
            'src' => 'pwa/1920x1920.svg',
        ],
    ];

    #[Test]
    public function relyingOnTheFaviconsToGenerateTheStartupImagesIsDeprecated(): void
    {
        $deprecations = $this->load([
            'favicons' => self::FAVICONS,
        ], $startupImages);

        static::assertTrue($startupImages['enabled'], 'the startup images are no longer generated');
        static::assertSame([
            'Since spomky-labs/pwa-bundle 1.6.0: The iOS startup images are generated by default when "pwa.favicons" is enabled. This default becomes false in 2.0.0. Set "pwa.startup_images.enabled" explicitly: true to keep generating them, false to stop.',
        ], $deprecations);
    }

    #[Test]
    #[DataProvider('choices')]
    public function choosingWhetherToGenerateTheStartupImagesIsNotDeprecated(bool $enabled): void
    {
        $deprecations = $this->load([
            'favicons' => self::FAVICONS,
            'startup_images' => [
                'enabled' => $enabled,
            ],
        ], $startupImages);

        static::assertSame($enabled, $startupImages['enabled']);
        static::assertSame([], $deprecations);
    }

    /**
     * @param array<string, mixed> $configuration
     */
    #[Test]
    #[DataProvider('withoutFavicons')]
    public function anApplicationGeneratingNoFaviconIsNotDeprecated(array $configuration): void
    {
        $deprecations = $this->load($configuration, $startupImages);

        static::assertFalse($startupImages['enabled']);
        static::assertSame([], $deprecations);
    }

    /**
     * "use_start_image" answers the same question, so an application that set it has made its choice. It is
     * only told about the key it used, which has its own deprecation.
     */
    #[Test]
    #[DataProvider('choices')]
    public function choosingThroughTheFaviconsIsOnlyReportedForTheKeyItUses(bool $useStartImage): void
    {
        $deprecations = $this->load([
            'favicons' => [
                ...self::FAVICONS,
                'use_start_image' => $useStartImage,
            ],
        ], $startupImages);

        static::assertSame($useStartImage, $startupImages['enabled']);
        static::assertSame([
            'Since spomky-labs/phpwa 1.6.0: The "use_start_image" configuration key is deprecated. Use the "pwa.startup_images.enabled" configuration key instead.',
        ], $deprecations);
    }

    /**
     * The explicit "startup_images.enabled" wins over "use_start_image", whatever the latter says.
     */
    #[Test]
    public function theStartupImagesSectionDecidesOverTheFavicons(): void
    {
        $this->load([
            'favicons' => [
                ...self::FAVICONS,
                'use_start_image' => false,
            ],
            'startup_images' => [
                'enabled' => true,
            ],
        ], $startupImages);

        static::assertTrue($startupImages['enabled']);
    }

    /**
     * Neither key may receive a value from the bundle itself: a default of true would be indistinguishable
     * from an explicit choice, and the deprecation would then never be reported.
     */
    #[Test]
    public function theBundleLeavesTheChoiceUndecided(): void
    {
        $config = (new Processor())->processConfiguration(
            new Configuration(new SpomkyLabsPwaBundle(), null, 'pwa'),
            [[
                'favicons' => self::FAVICONS,
            ]]
        );

        static::assertNull($config['favicons']['use_start_image']);
        static::assertNull($config['startup_images']['enabled']);
    }

    /**
     * @return iterable<string, array{bool}>
     */
    public static function choices(): iterable
    {
        yield 'enabled' => [true];
        yield 'disabled' => [false];
    }

    /**
     * @return iterable<string, array{array<string, mixed>}>
     */
    public static function withoutFavicons(): iterable
    {
        yield 'no configuration' => [[]];
        yield 'favicons disabled' => [[
            'favicons' => [
                ...self::FAVICONS,
                'enabled' => false,
            ],
        ]];
        yield 'manifest only' => [[
            'manifest' => [
                'enabled' => true,
            ],
        ]];
    }

    /**
     * Loads the bundle extension, as the kernel does when it builds the container.
     *
     * @param array<string, mixed>      $configuration
     * @param array<string, mixed>|null $startupImages the startup images configuration the bundle resolved
     *
     * @return list<string> the deprecations about the startup images
     */
    private function load(array $configuration, null|array &$startupImages = null): array
    {
        $container = new ContainerBuilder();
        $container->setParameter('kernel.environment', 'test');
        $extension = (new SpomkyLabsPwaBundle())->getContainerExtension();
        static::assertNotNull($extension);

        $deprecations = [];
        set_error_handler(static function (int $level, string $message) use (&$deprecations): bool {
            $deprecations[] = $message;

            return true;
        }, E_USER_DEPRECATED);

        try {
            $extension->load([$configuration], $container);
        } finally {
            restore_error_handler();
        }

        /** @var array<string, mixed> $startupImages */
        $startupImages = $container->getParameter('spomky_labs_pwa.startup_images.config');

        return array_values(array_filter(
            $deprecations,
            static fn (string $message): bool => str_contains($message, 'startup')
        ));
    }
}
